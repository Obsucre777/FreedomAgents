'use strict'

/**
 * workspace —— 项目目录相关的底层工具
 *
 *  - 找仓库根（从 cwd 向上找 .freedomagents/）
 *  - agents/*.yaml 的读写（迷你 YAML，只处理平铺 key: value）
 *  - 8 位随机 id
 *  - create 短锁（保护「查重 + 分配 id + 写文件」）
 */

const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const STATE_DIR = '.freedomagents'
const LOCK_TIMEOUT_MS = 2000
const LOCK_STALE_MS = 30000
const ID_RETRIES = 20

function isDirectory(target) {
  try {
    return fs.statSync(target).isDirectory()
  } catch {
    return false
  }
}

function stateDir(root) {
  return path.join(root, STATE_DIR)
}

function agentsDir(root) {
  return path.join(root, 'agents')
}

function createLockPath(root) {
  return path.join(stateDir(root), 'create.lock')
}

/** 从 start 向上找包含 .freedomagents/ 的目录 */
function findRoot(start = process.cwd()) {
  let current = path.resolve(start)
  for (;;) {
    if (isDirectory(path.join(current, STATE_DIR))) return current
    const parent = path.dirname(current)
    if (parent === current) return null
    current = parent
  }
}

function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms)
}

function processAlive(pid) {
  if (!Number.isInteger(pid) || pid <= 0) return false
  try {
    process.kill(pid, 0)
    return true
  } catch (err) {
    return err.code === 'EPERM'
  }
}

function isLockStale(lockPath) {
  try {
    const stat = fs.statSync(lockPath)
    if (Date.now() - stat.mtimeMs > LOCK_STALE_MS) return true
    try {
      const meta = JSON.parse(fs.readFileSync(lockPath, 'utf8'))
      if (meta && typeof meta.pid === 'number' && !processAlive(meta.pid)) return true
    } catch {
      /* 内容损坏的锁按过期处理 */
    }
    return false
  } catch (err) {
    return err.code !== 'ENOENT'
  }
}

/** create 临界区锁：独占创建 create.lock，等待超时报冲突（退出码 2） */
function withCreateLock(root, fn) {
  const lock = createLockPath(root)
  const startedAt = Date.now()
  let fd = null

  for (;;) {
    try {
      fd = fs.openSync(lock, 'wx', 0o600)
      break
    } catch (err) {
      if (err.code !== 'EEXIST') throw err
      if (isLockStale(lock)) {
        try {
          fs.unlinkSync(lock)
        } catch {
          /* 别人抢先回收了 */
        }
        continue
      }
      if (Date.now() - startedAt > LOCK_TIMEOUT_MS) {
        const conflict = new Error('另一个 fa create 正在执行，请稍后重试')
        conflict.exitCode = 2
        throw conflict
      }
      sleep(20)
    }
  }

  try {
    fs.writeFileSync(fd, JSON.stringify({ pid: process.pid, ts: Date.now() }))
    fs.fsyncSync(fd)
    return fn()
  } finally {
    try {
      fs.closeSync(fd)
    } catch {
      /* ignore */
    }
    try {
      fs.unlinkSync(lock)
    } catch {
      /* ignore */
    }
  }
}

function gitignoreHasStateDir(content) {
  return content
    .split(/\r?\n/)
    .some((line) => line.trim() === `${STATE_DIR}/` || line.trim() === STATE_DIR)
}

/** 确保 .gitignore 忽略运行状态目录（不覆盖已有内容，不重复添加） */
function ensureGitignore(root) {
  const file = path.join(root, '.gitignore')
  let current = ''
  try {
    current = fs.readFileSync(file, 'utf8')
  } catch (err) {
    if (err.code !== 'ENOENT') throw err
  }
  if (gitignoreHasStateDir(current)) return false

  const prefix = current.length > 0 && !current.endsWith('\n') ? '\n' : ''
  fs.writeFileSync(file, `${current}${prefix}${STATE_DIR}/\n`)
  return true
}

/** 迷你 YAML 读取：只解析我们生成的平铺 key: value（值可能是 JSON 字符串） */
function parseFlatYaml(text) {
  const map = {}
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const index = line.indexOf(':')
    if (index === -1) continue
    const key = line.slice(0, index).trim()
    let value = line.slice(index + 1).trim()
    if (value.startsWith('"')) {
      try {
        value = JSON.parse(value)
      } catch {
        /* 保持原样 */
      }
    }
    map[key] = value
  }
  return map
}

function listAgents(root) {
  const dir = agentsDir(root)
  let entries = []
  try {
    entries = fs.readdirSync(dir)
  } catch (err) {
    if (err.code === 'ENOENT') return []
    throw err
  }

  const agents = []
  for (const entry of entries) {
    if (!entry.endsWith('.yaml')) continue
    const file = path.join(dir, entry)
    try {
      agents.push({ file, ...parseFlatYaml(fs.readFileSync(file, 'utf8')) })
    } catch {
      /* 跳过无法解析的文件 */
    }
  }
  return agents
}

/** 8 位随机 hex id，保证不与现有文件冲突 */
function generateId(dir) {
  for (;;) {
    const id = crypto.randomBytes(4).toString('hex')
    if (!fs.existsSync(path.join(dir, `${id}.yaml`))) return id
  }
}

function serializeAgent({ id, name, role, harness }) {
  return [
    '# FreedomAgents agent — generated by `fa create`',
    `id: ${JSON.stringify(id)}`,
    `name: ${JSON.stringify(name)}`,
    `role: ${JSON.stringify(role)}`,
    `harness: ${JSON.stringify(harness)}`,
    `created_at: ${JSON.stringify(new Date().toISOString())}`,
    '',
  ].join('\n')
}

/** 写 agents/<id>.yaml（独占创建，撞 id 自动重试） */
function writeAgent(root, fields) {
  const dir = agentsDir(root)
  fs.mkdirSync(dir, { recursive: true })

  for (let attempt = 0; attempt < ID_RETRIES; attempt += 1) {
    const id = generateId(dir)
    const file = path.join(dir, `${id}.yaml`)
    let fd = null
    try {
      fd = fs.openSync(file, 'wx', 0o600)
      fs.writeFileSync(fd, serializeAgent({ id, ...fields }))
      return { id, file }
    } catch (err) {
      if (err.code !== 'EEXIST') throw err
    } finally {
      if (fd !== null) {
        try {
          fs.closeSync(fd)
        } catch {
          /* ignore */
        }
      }
    }
  }

  throw new Error('无法分配 agent id，请重试')
}

module.exports = {
  STATE_DIR,
  findRoot,
  stateDir,
  agentsDir,
  createLockPath,
  ensureGitignore,
  gitignoreHasStateDir,
  withCreateLock,
  parseFlatYaml,
  listAgents,
  generateId,
  writeAgent,
}
